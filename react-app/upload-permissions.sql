create table if not exists public.visitor_upload_permissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  visitor_id text not null,
  visitor_name text not null,
  request_note text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'ignored', 'revoked')),
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id)
);

alter table public.visitor_upload_permissions enable row level security;

drop policy if exists visitor_upload_permissions_select_own on public.visitor_upload_permissions;
create policy visitor_upload_permissions_select_own
on public.visitor_upload_permissions
for select to authenticated
using (auth.uid() = user_id);

drop policy if exists visitor_upload_permissions_insert_own on public.visitor_upload_permissions;
create policy visitor_upload_permissions_insert_own
on public.visitor_upload_permissions
for insert to authenticated
with check (auth.uid() = user_id and status = 'pending');

drop policy if exists visitor_upload_permissions_update_own on public.visitor_upload_permissions;
create policy visitor_upload_permissions_update_own
on public.visitor_upload_permissions
for update to authenticated
using (auth.uid() = user_id and status <> 'approved')
with check (auth.uid() = user_id and status = 'pending');

drop policy if exists visitor_upload_permissions_admin_select on public.visitor_upload_permissions;
create policy visitor_upload_permissions_admin_select
on public.visitor_upload_permissions
for select to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists visitor_upload_permissions_admin_update on public.visitor_upload_permissions;
create policy visitor_upload_permissions_admin_update
on public.visitor_upload_permissions
for update to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

alter table public.photos enable row level security;
drop policy if exists photos_insert_approved_visitor on public.photos;
create policy photos_insert_approved_visitor
on public.photos
for insert to authenticated
with check (
  exists (
    select 1
    from public.visitor_upload_permissions p
    where p.user_id = auth.uid()
      and p.status = 'approved'
  )
  or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);

drop policy if exists photos_insert_admin on public.photos;
create policy photos_insert_admin
on public.photos
for insert to authenticated
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- Run this policy only if the photos bucket should be writable by approved visitors.
drop policy if exists photos_storage_insert_approved_visitor on storage.objects;
create policy photos_storage_insert_approved_visitor
on storage.objects
for insert to authenticated
with check (
  bucket_id = 'photos'
  and (
    exists (
      select 1
      from public.visitor_upload_permissions p
      where p.user_id = auth.uid()
        and p.status = 'approved'
    )
    or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  )
);

